using System.IO.Abstractions.TestingHelpers;
using System.Text.Json;
using DrillPress.BundleVerification;
using DrillPress.Manifest;
using DrillPress.UnitTests.TestInfrastructure;
using Xunit;

namespace DrillPress.UnitTests.DrillPress.BundleVerification;

public sealed class SourceGeneratorCatalogWriterTests
{
    [Fact]
    public void Native_catalogue_selects_one_assembly_version_and_preserves_its_fingerprint()
    {
        var files = new MockFileSystem();
        files.AddFile(
            "/old/Generators.dll",
            new MockFileData(MetadataOnlyAssembly.Create("Generators", new Version(1, 0, 0, 0)))
        );
        files.AddFile(
            "/new/Generators.dll",
            new MockFileData(MetadataOnlyAssembly.Create("Generators", new Version(2, 0, 0, 0)))
        );
        var fingerprint = new string('B', 64);
        var inventory = new GeneratorBuildInventory(
            ComponentVersion.Current,
            [
                new(
                    new(
                        "Sample.OldGenerator",
                        "Generators, Version=1.0.0.0, Culture=neutral, PublicKeyToken=null",
                        new string('A', 64)
                    ),
                    "/old/Generators.dll",
                    true,
                    true
                ),
                new(
                    new(
                        "Sample.NewGenerator",
                        "Generators, Version=2.0.0.0, Culture=neutral, PublicKeyToken=null",
                        fingerprint
                    ),
                    "/new/Generators.dll",
                    true,
                    true
                ),
            ],
            []
        );
        files.AddFile(
            "/inventory.json",
            new MockFileData(
                JsonSerializer.SerializeToUtf8Bytes(
                    inventory,
                    GeneratorPlanJsonContext.Default.GeneratorBuildInventory
                )
            )
        );

        new SourceGeneratorCatalogWriter(files).Write("/inventory.json", "/catalogue");

        Assert.Equal(
            """
            // <auto-generated/>
            extern alias generator0;
            using Microsoft.CodeAnalysis;
            [assembly: global::DrillPress.Engine.SourceGeneratorCatalogAttribute(typeof(global::DrillPress.Generated.BundleSourceGenerators))]
            namespace DrillPress.Generated;
            /// <summary>Source generators linked from the target's verified compiler inventory.</summary>
            public sealed class BundleSourceGenerators : global::DrillPress.Engine.SourceGeneratorCatalog
            {
            /// <summary>Creates the exact generator implementations selected when publishing this bundle.</summary>
            public BundleSourceGenerators() : base([
            new global::DrillPress.Engine.CompiledSourceGenerator(new generator0::@Sample.@NewGenerator().AsSourceGenerator(), "BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB"),
            ]) {}
            }

            """.ReplaceLineEndings("\n"),
            files.File.ReadAllText("/catalogue/SourceGenerators.g.cs")
        );
        Assert.Equal(
            "/new/Generators.dll\n",
            files.File.ReadAllText("/catalogue/assembly-inputs.txt")
        );
    }
}
